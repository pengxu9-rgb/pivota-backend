"""RFC 9421 request signing for Pivota's OUTBOUND UCP calls (Pivota as the platform/agent).

WHY THIS EXISTS. Shopline's agent standard (designed with Meta's Muse, 2026-11-20) treats Pivota
exactly like Muse: a platform is identified by the `UCP-Agent` profile it names on every request,
and the request is signed with a key that profile publishes (`signing_keys[]` / `keys[]`, matched
by `kid`). The backend's checkout client (services/merchant_ucp_checkout.py) sent only
`meta["ucp-agent"]` -- no header, no signature, no Content-Digest -- so a merchant enforcing the
standard refuses it.

ONE IDENTITY, TWO SIGNERS. The gateway already signs (PIVOTA-Agent
src/services/ucpBuyerAgentClient.js, buildUcpSignatureBase / signUcpRequest). This module is its
Python twin and must agree with it BYTE FOR BYTE: tests/fixtures/ucp_request_signature_vectors.json
is generated by the gateway signer and reproduced here by tests/test_ucp_request_signing.py.

THE CONSTRUCTION (ucp.dev/2026-04-08/specification/signatures):
  - covered, in order: "@method" "@authority" "@path" ["@query"] ["ucp-agent"] ["idempotency-key"]
    ["content-digest" "content-type"] -- each optional one only when present;
  - Content-Digest: RFC 9530 `sha-256=:<base64>:` over the exact body bytes (sha-256 only);
  - Signature-Input: `sig1=(<components>);created=<ts>;expires=<ts>;keyid="<kid>"`, NO `alg`
    (verifiers derive it from the JWK's crv);
  - Signature: `sig1=:<base64(raw r||s)>:` -- ECDSA P-256 as fixed-width 64 bytes, NOT DER.

KEY MATERIAL comes from env only (UCP_AGENT_SIGNING_PRIVATE_KEY: PEM or a private JWK;
UCP_AGENT_SIGNING_KEY_ID, else the JWK's kid) and is never logged, returned or put in an error.
"""

from __future__ import annotations

import base64
import hashlib
import json
import logging
import os
import time
from typing import Any, Dict, List, Optional, Tuple
from urllib.parse import urlsplit

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils

logger = logging.getLogger(__name__)

SIGNATURE_TTL_SECONDS = 300
CONTENT_TYPE = "application/json"
_DEFAULT_PORTS = {"https": 443, "http": 80}

# (raw env value, kid env value) -> (key, kid). The raw value is the cache key so a rotated secret
# takes effect on the next call without a restart; it is never logged.
_key_cache: Dict[Tuple[str, str], Tuple[ec.EllipticCurvePrivateKey, str]] = {}


class SigningKeyError(ValueError):
    """The configured signing key cannot be used. The message never contains key material."""


def _b64url_int(value: str) -> int:
    pad = "=" * (-len(value) % 4)
    return int.from_bytes(base64.urlsafe_b64decode(value + pad), "big")


def load_signing_key(
    raw: Optional[str] = None, kid: Optional[str] = None
) -> Optional[Tuple[ec.EllipticCurvePrivateKey, str]]:
    """The ECDSA P-256 private key and its kid, or None when no key is configured."""
    raw = (raw if raw is not None else os.getenv("UCP_AGENT_SIGNING_PRIVATE_KEY") or "").strip()
    kid = (kid if kid is not None else os.getenv("UCP_AGENT_SIGNING_KEY_ID") or "").strip()
    if not raw:
        return None
    cached = _key_cache.get((raw, kid))
    if cached:
        return cached
    jwk_kid = ""
    if raw.startswith("{"):
        try:
            jwk = json.loads(raw)
        except ValueError:
            raise SigningKeyError("UCP_AGENT_SIGNING_PRIVATE_KEY is not valid JSON (JWK)") from None
        if not isinstance(jwk, dict) or jwk.get("kty") != "EC" or jwk.get("crv") != "P-256" or not jwk.get("d"):
            raise SigningKeyError("signing JWK must be a private EC P-256 key")
        try:
            key = ec.derive_private_key(_b64url_int(str(jwk["d"])), ec.SECP256R1())
        except Exception:
            raise SigningKeyError("signing JWK private component is unusable") from None
        jwk_kid = str(jwk.get("kid") or "").strip()
    else:
        try:
            key = serialization.load_pem_private_key(raw.encode("utf-8"), password=None)
        except Exception:
            raise SigningKeyError("UCP_AGENT_SIGNING_PRIVATE_KEY is not a readable PEM key") from None
        if not isinstance(key, ec.EllipticCurvePrivateKey) or not isinstance(key.curve, ec.SECP256R1):
            raise SigningKeyError("signing key must be ECDSA P-256")
    resolved_kid = kid or jwk_kid
    if not resolved_kid:
        raise SigningKeyError(
            "UCP signing key present but no keyid: set UCP_AGENT_SIGNING_KEY_ID or embed kid in the JWK"
        )
    _key_cache.clear()  # one live key at a time; a rotated value replaces, never accumulates
    _key_cache[(raw, kid)] = (key, resolved_kid)
    return key, resolved_kid


def content_digest(body: bytes) -> str:
    """RFC 9530 Content-Digest. Always sha-256, over the exact bytes sent."""
    return "sha-256=:" + base64.b64encode(hashlib.sha256(body).digest()).decode("ascii") + ":"


def _authority(parts) -> str:
    # The gateway uses WHATWG `URL.host`: lower-cased hostname, port only when not the scheme's default.
    host = (parts.hostname or "").lower()
    port = parts.port
    if port is not None and port != _DEFAULT_PORTS.get(parts.scheme.lower()):
        host = f"{host}:{port}"
    return host


def build_signature_base(
    *,
    method: str,
    url: str,
    body: Optional[bytes],
    ucp_agent: Optional[str],
    idempotency_key: Optional[str],
    keyid: str,
    created: Optional[int],
    expires: Optional[int],
) -> Dict[str, Any]:
    """RFC 9421 signature base + Signature-Input params. Pure; mirrors the gateway's buildUcpSignatureBase."""
    parts = urlsplit(url)
    digest = content_digest(body) if body is not None else None
    fields: List[Tuple[str, str]] = [
        ("@method", str(method or "POST").upper()),
        ("@authority", _authority(parts)),
        ("@path", parts.path or "/"),
    ]
    if parts.query:
        fields.append(("@query", "?" + parts.query))
    if ucp_agent:
        fields.append(("ucp-agent", ucp_agent))
    if idempotency_key:
        fields.append(("idempotency-key", idempotency_key))
    if digest:
        fields.append(("content-digest", digest))
    if body is not None:
        fields.append(("content-type", CONTENT_TYPE))
    covered = [name for name, _ in fields]
    params = "(" + " ".join(f'"{n}"' for n in covered) + ")"
    if created is not None:
        params += f";created={created}"
    if expires is not None:
        params += f";expires={expires}"
    params += f';keyid="{keyid}"'
    lines = [f'"{name}": {value}' for name, value in fields]
    lines.append(f'"@signature-params": {params}')
    return {"base": "\n".join(lines), "params": params, "covered": covered, "content_digest": digest}


def sign(base: str, key: ec.EllipticCurvePrivateKey) -> bytes:
    """ECDSA P-256 / SHA-256 over the base, as raw r||s (64 bytes) -- never DER."""
    der = key.sign(base.encode("utf-8"), ec.ECDSA(hashes.SHA256()))
    r, s = utils.decode_dss_signature(der)
    return r.to_bytes(32, "big") + s.to_bytes(32, "big")


def ucp_agent_header(profile_url: str) -> str:
    """The RFC 8941 Dictionary form of the UCP-Agent header."""
    return f'profile="{profile_url}"'


def signed_request_headers(
    *,
    method: str,
    url: str,
    body: Optional[bytes],
    profile_url: str,
    idempotency_key: Optional[str],
    key: ec.EllipticCurvePrivateKey,
    keyid: str,
    now: Optional[int] = None,
    ttl_seconds: int = SIGNATURE_TTL_SECONDS,
) -> Dict[str, str]:
    """Every header a signed UCP call carries: UCP-Agent, Idempotency-Key, Content-Type,
    Content-Digest, Signature-Input, Signature. Signed for exactly this URL, so a hop re-signs."""
    created = int(now if now is not None else time.time())
    ucp_agent = ucp_agent_header(profile_url)
    built = build_signature_base(
        method=method,
        url=url,
        body=body,
        ucp_agent=ucp_agent,
        idempotency_key=idempotency_key,
        keyid=keyid,
        created=created,
        expires=created + ttl_seconds,
    )
    headers = {"ucp-agent": ucp_agent}
    if idempotency_key:
        headers["idempotency-key"] = idempotency_key
    if body is not None:
        headers["content-type"] = CONTENT_TYPE
        headers["content-digest"] = built["content_digest"]
    headers["signature-input"] = "sig1=" + built["params"]
    headers["signature"] = "sig1=:" + base64.b64encode(sign(built["base"], key)).decode("ascii") + ":"
    return headers
