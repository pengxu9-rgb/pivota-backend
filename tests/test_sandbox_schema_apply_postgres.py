"""Prod schema -> sandbox, end to end against REAL Postgres and the REAL pg_dump.

    PG_BIN_DIR=/opt/homebrew/opt/postgresql@15/bin \\
    DATABASE_URL=postgresql://postgres@localhost:5432/pivota_sandbox_copy_test \\
        .venv/bin/python -m pytest tests/test_sandbox_schema_apply_postgres.py

Skips without a Postgres DATABASE_URL or without pg_dump/psql (PG_BIN_DIR, else PATH). Creates two
throwaway databases next to DATABASE_URL's (pivota_schema_src_test, pivota_schema_dst_test), runs
scripts/sandbox/dump_prod_schema.sh against the source into a directory, applies it to the empty
target with jobs/sandbox_schema_apply.apply_schema, and requires pg_dump --schema-only of the two to
be IDENTICAL. Does not import `main`.
"""

from __future__ import annotations

import gzip
import os
import shutil
import subprocess
from pathlib import Path

import pytest

DATABASE_URL = (os.getenv("DATABASE_URL") or "").strip()
_IS_PG = DATABASE_URL.startswith(("postgresql://", "postgres://"))
BIN = (os.getenv("PG_BIN_DIR") or "").strip()
PG_DUMP = os.path.join(BIN, "pg_dump") if BIN else shutil.which("pg_dump")
PSQL = os.path.join(BIN, "psql") if BIN else shutil.which("psql")
pytestmark = pytest.mark.skipif(
    not (_IS_PG and PG_DUMP and os.path.exists(PG_DUMP) and PSQL and os.path.exists(PSQL)),
    reason="needs a Postgres DATABASE_URL and pg_dump/psql (PG_BIN_DIR)",
)
if _IS_PG:
    _db = DATABASE_URL.rsplit("/", 1)[-1].split("?")[0]
    if not any(m in _db for m in ("dialect_check", "_test", "test_")):
        pytest.skip("throwaway database only", allow_module_level=True)

from jobs import sandbox_schema_apply as A  # noqa: E402
from jobs.sandbox_catalog_copy import LocalDirStore  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/sandbox/dump_prod_schema.sh"
BASE = DATABASE_URL.rsplit("/", 1)[0]
SRC_DB, DST_DB = "pivota_schema_src_test", "pivota_schema_dst_test"
SRC, DST = "%s/%s" % (BASE, SRC_DB), "%s/%s" % (BASE, DST_DB)
STAMP = "20261125T2300Z"
ROW_SECRET = "row-value-that-must-never-leave"

SOURCE_DDL = """
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE TYPE offer_state AS ENUM ('live', 'paused');
CREATE DOMAIN currency_code AS CHAR(3) CHECK (VALUE ~ '^[A-Z]{3}$');
CREATE TABLE merchants (merchant_id TEXT PRIMARY KEY, name TEXT NOT NULL, contact_email TEXT);
CREATE TABLE offers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id TEXT NOT NULL REFERENCES merchants(merchant_id) ON DELETE CASCADE,
  title TEXT NOT NULL, title_lower TEXT GENERATED ALWAYS AS (lower(title)) STORED,
  price NUMERIC(12,4) NOT NULL CHECK (price >= 0), currency currency_code NOT NULL,
  state offer_state NOT NULL DEFAULT 'live', tags TEXT[], attrs JSONB, token UUID DEFAULT gen_random_uuid(),
  price_checked_at TIMESTAMPTZ);
CREATE UNIQUE INDEX offers_live_title ON offers (merchant_id, title_lower) WHERE state = 'live';
CREATE TABLE offer_audit (id SERIAL PRIMARY KEY, offer_id BIGINT, note TEXT, at TIMESTAMPTZ DEFAULT now());
CREATE FUNCTION clear_price_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.price IS DISTINCT FROM OLD.price THEN NEW.price_checked_at := NULL; END IF;
  INSERT INTO offer_audit (offer_id, note) VALUES (NEW.id, 'price moved');
  RETURN NEW;
END $$;
CREATE TRIGGER offers_clear_price_check BEFORE UPDATE ON offers FOR EACH ROW EXECUTE FUNCTION clear_price_check();
CREATE VIEW live_offers AS SELECT id, merchant_id, price FROM offers WHERE state = 'live';
CREATE TABLE startup_sql_migrations (filename TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE schema_migrations (id TEXT PRIMARY KEY, applied_at TIMESTAMPTZ DEFAULT now());
INSERT INTO startup_sql_migrations (filename, checksum) VALUES ('001_a.sql', 'c1'), ('002_b.sql', 'c2');
INSERT INTO schema_migrations (id) VALUES ('001_taxonomy.sql'), ('052_commerce_kv.sql'), ('071_x.sql');
COMMENT ON TABLE merchants IS 'comment-that-must-never-leave';
GRANT SELECT ON merchants TO PUBLIC;
INSERT INTO merchants VALUES ('m1', 'Brand', 'owner@person.example');
INSERT INTO offers (merchant_id, title, price, currency, attrs) VALUES ('m1', 'Lip', 9.5, 'USD', '{"note": "%s"}');
""" % ROW_SECRET


async def _admin():
    import asyncpg

    return await asyncpg.connect(DATABASE_URL)


async def _recreate(admin, name):
    await admin.execute('DROP DATABASE IF EXISTS "%s"' % name)
    await admin.execute('CREATE DATABASE "%s"' % name)


@pytest.fixture
async def dbs():
    import asyncpg

    admin = await _admin()
    for name in (SRC_DB, DST_DB):
        await _recreate(admin, name)
    src = await asyncpg.connect(SRC)
    await src.execute(SOURCE_DDL)
    await src.close()
    try:
        yield
    finally:
        for name in (SRC_DB, DST_DB):
            await admin.execute('DROP DATABASE IF EXISTS "%s" WITH (FORCE)' % name)
        await admin.close()


def _dump(tmp_path, *, dsn=SRC, env_extra=None):
    env = {"PATH": "%s:%s" % (os.path.dirname(PG_DUMP), os.environ.get("PATH", "")), "HOME": str(tmp_path),
           "PIVOTA_ENV": "production", "DATABASE_URL": dsn, "STAMP": STAMP,
           "SCHEMA_DUMP_LOCAL_OUT_DIR": str(tmp_path / "drop")}
    env.update(env_extra or {})
    return subprocess.run(["bash", str(SCRIPT)], env=env, capture_output=True, text=True, timeout=300)


def _schema_of(dsn):
    out = subprocess.run([PG_DUMP, dsn, "--schema-only", "--no-owner", "--no-privileges", "--no-comments"],
                         capture_output=True, text=True, check=True).stdout
    return "\n".join(line for line in out.splitlines()
                     if not line.startswith(("\\restrict", "\\unrestrict", "-- Dumped ")))


async def test_the_sandbox_gets_prods_schema_exactly_and_no_rows(dbs, tmp_path):
    import asyncpg

    done = _dump(tmp_path)
    assert done.returncode == 0, done.stderr
    assert "DONE" in done.stdout and "postgresql://" not in done.stdout + done.stderr
    files = sorted(p.name for p in (tmp_path / "drop" / STAMP).iterdir())
    assert files == ["_MANIFEST.json", "ledgers.sql.gz", "schema.sql.gz"]
    blob = b"".join(gzip.decompress((tmp_path / "drop" / STAMP / f).read_bytes()) for f in ("schema.sql.gz", "ledgers.sql.gz"))
    assert ROW_SECRET.encode() not in blob and b"owner@person.example" not in blob
    assert b"comment-that-must-never-leave" not in blob and b"GRANT " not in blob

    dst = await asyncpg.connect(DST)
    try:
        report = await A.apply_schema(dst, LocalDirStore(tmp_path / "drop"))
        assert report["stamp"] == STAMP and report["ledger_rows"] == 5
        assert await dst.fetchval("SELECT count(*) FROM merchants") == 0
        assert await dst.fetchval("SELECT count(*) FROM offers") == 0
        assert await dst.fetchval("SELECT count(*) FROM schema_migrations") == 3
        assert await dst.fetchval("SELECT count(*) FROM startup_sql_migrations") == 2
        # The schema works: identity, generated column, domain, enum, trigger all live.
        await dst.execute("INSERT INTO merchants VALUES ('s1', 'Sandbox brand', NULL)")
        await dst.execute("INSERT INTO offers (merchant_id, title, price, currency, price_checked_at) "
                          "VALUES ('s1', 'Tint', 5, 'USD', now())")
        await dst.execute("UPDATE offers SET price = 6")
        row = await dst.fetchrow("SELECT title_lower, price_checked_at FROM offers")
        assert row["title_lower"] == "tint" and row["price_checked_at"] is None
        with pytest.raises(asyncpg.exceptions.CheckViolationError):
            await dst.execute("INSERT INTO offers (merchant_id, title, price, currency) VALUES ('s1', 'x', 1, 'usd')")
    finally:
        await dst.close()
    assert _schema_of(SRC) == _schema_of(DST)


async def test_a_populated_sandbox_is_never_touched(dbs, tmp_path):
    import asyncpg

    assert _dump(tmp_path).returncode == 0
    dst = await asyncpg.connect(DST)
    try:
        await dst.execute("CREATE TABLE already_here (id int)")
        with pytest.raises(A.SchemaRefused, match="not empty"):
            await A.apply_schema(dst, LocalDirStore(tmp_path / "drop"))
        assert await dst.fetchval("SELECT to_regclass('public.offers')") is None
    finally:
        await dst.close()


async def test_a_failing_apply_leaves_the_sandbox_empty(dbs, tmp_path):
    import asyncpg

    assert _dump(tmp_path).returncode == 0
    dst = await asyncpg.connect(DST)
    try:
        # A table count the source never had: the post-check fails and everything rolls back.
        import json

        path = tmp_path / "drop" / STAMP / "_MANIFEST.json"
        manifest = json.loads(path.read_text())
        manifest["tables_live"] += 1
        path.write_text(json.dumps(manifest))
        with pytest.raises(A.SchemaRefused, match="tables after apply"):
            await A.apply_schema(dst, LocalDirStore(tmp_path / "drop"))
        assert await A._user_table_count(dst) == 0
    finally:
        await dst.close()


async def test_a_credential_in_the_schema_never_leaves_prod(dbs, tmp_path):
    import asyncpg

    src = await asyncpg.connect(SRC)
    try:
        try:
            await src.execute("CREATE EXTENSION IF NOT EXISTS postgres_fdw")
        except asyncpg.exceptions.PostgresError:
            pytest.skip("postgres_fdw not available here")
        await src.execute("CREATE SERVER other FOREIGN DATA WRAPPER postgres_fdw OPTIONS (host 'db.example', dbname 'x')")
        await src.execute("CREATE USER MAPPING FOR CURRENT_USER SERVER other OPTIONS (user 'u', password 'fdw-SECRET')")
    finally:
        await src.close()
    done = _dump(tmp_path)
    assert done.returncode == 3, done.stdout + done.stderr
    assert "forbidden statement" in done.stderr and "fdw-SECRET" not in done.stdout + done.stderr
    assert not (tmp_path / "drop").exists()


async def test_the_dump_refuses_to_run_outside_production(dbs, tmp_path):
    for label in ("sandbox", "staging", ""):
        done = _dump(tmp_path, env_extra={"PIVOTA_ENV": label})
        assert done.returncode == 2 and "PIVOTA_ENV=production" in done.stderr
    assert not (tmp_path / "drop").exists()


async def test_a_dump_never_overwrites_a_stamp(dbs, tmp_path):
    assert _dump(tmp_path).returncode == 0
    again = _dump(tmp_path)
    assert again.returncode != 0 and "never overwrites" in again.stderr
