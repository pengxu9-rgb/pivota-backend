def _dump(tmp_path, *, dsn=DUMPER, env_extra=None):
    env = {"PATH": "%s:%s" % (os.path.dirname(PG_DUMP), os.environ.get("PATH", "")), "HOME": str(tmp_path),
           "PIVOTA_ENV": "production", "DATABASE_URL": dsn, "STAMP": STAMP,
           "SCHEMA_DUMP_LOCAL_OUT_DIR": str(tmp_path / "drop")}
    env.update(env_extra or {})
    return subprocess.run(["bash", str(SCRIPT)], env=env, capture_output=True, text=True, timeout=300)


def _schema_of(dsn):
    out = subprocess.run([PG_DUMP, dsn, "--schema-only", "--no-owner", "--no-privileges", "--no-comments"],
                         capture_output=True, text=True, check=True).stdout
    return "\n".join(line for line in out.splitlines()
                     if not line.startswith(("\\restrict", "\\unrestrict", "-- Dumped ")))


