        assert await dst.fetchval("SELECT count(*) FROM merchants") == 0
        assert await dst.fetchval("SELECT count(*) FROM offers") == 0
        assert await dst.fetchval("SELECT count(*) FROM schema_migrations") == 3
        assert await dst.fetchval("SELECT count(*) FROM startup_sql_migrations") == 2
