async def _bootstrap_dump_role(admin):
    import asyncpg

    await admin.execute("CREATE ROLE \"%s\" LOGIN NOINHERIT PASSWORD '%s'" % (DUMP_ROLE, DUMP_PASSWORD))
    await admin.execute('ALTER ROLE "%s" SET default_transaction_read_only = on' % DUMP_ROLE)
