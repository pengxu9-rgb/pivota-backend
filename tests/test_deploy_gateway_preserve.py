"""`infra/gcp/deploy_gateway.sh` — the prod gateway deploy path.

WHY THIS EXISTS. Until 2026-08-25 this script could not deploy the production gateway at all. It
hard-required `env.prod.gateway.yaml` and `secrets.prod.gateway.list`, which are git-ignored and
generated by `port_railway_env.py` from `railway variables --json` — and Railway was decommissioned
at the 2026-08-22 cutover. Every run of the script ended at that `exit 1`.

An unusable deploy script does not stop deploys. The gateway was deployed by hand with `gcloud`
instead, which runs NONE of the gates this file exists for:

  * `sweep_stale_tags()` never ran, so three tagged revisions sat pinned at minScale 2 running old
    code against live secrets until they were swept by hand;
  * `gcloud run deploy --image X` with no env flag inherits the previous revision's environment, so
    one revision carried `PIVOTA_COMMIT_SHA=6aa49526db95` on an image built from `17e7cfa8` —
    /health under-reported the deployed commit by 7 and the drift alarm reasoned about the wrong one.

So these tests are about the two properties that make the script usable and honest:

  1. a prod deploy ships CODE ONLY — it must never re-derive the live service's 382 environment
     variables from the retired platform as a side effect of shipping a commit; and
  2. the image tag and the stamped commit are the same value, written on EVERY deploy, so the
     revision cannot inherit a stale stamp.

The script is driven END TO END with `gcloud` and `curl` stubbed, and the assertions read the
recorded argv of the real `gcloud run deploy` / `update-traffic` calls. Asserting on the script's
TEXT instead would pass for a flag that is constructed and then never passed.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SCRIPT = REPO / "infra" / "gcp" / "deploy_gateway.sh"

SHA = "17e7cfa8b91c4d2e6f0a3b5d8c7e9f1a2b3c4d5e"
OTHER_SHA = "6aa49526db95c1d2e3f4a5b6c7d8e9f0a1b2c3d4"
CANDIDATE_TAG = "c-" + SHA[-12:]

# One stale tag (no percent) plus the live 100% one. sweep_stale_tags must remove only the first:
# the JSON shape is what the script's inline python parses, and `percent` absent/0 is "stale".
TRAFFIC_JSON = (
    '{"status":{"traffic":['
    '{"tag":"c-oldoldoldold","revisionName":"gateway-00010-mar"},'
    '{"tag":"' + CANDIDATE_TAG + '","percent":100,"revisionName":"gateway-00042-xyz"}'
    "]}}"
)

GCLOUD_STUB = r"""#!/bin/sh
# Record the whole invocation, argv boundaries intact (tab-separated; no argument contains a tab).
{
  first=1
  for a in "$@"; do
    if [ "$first" = 1 ]; then printf '%s' "$a"; first=0; else printf '\t%s' "$a"; fi
  done
  printf '\n'
} >> "$STUB_CALLS"

case "$1 $2" in
  "run services")
    case "$3" in
      describe)
        case "$*" in
          *"--format=json"*)      printf '%s' "$STUB_TRAFFIC_JSON"; exit 0 ;;
          *"traffic.extract"*)    printf '%s\n' "$STUB_CAND_URL";   exit 0 ;;
          *"value(status.url)"*)  printf '%s\n' "$STUB_SERVICE_URL"; exit 0 ;;
          *)                      exit "$STUB_SERVICE_EXISTS_RC" ;;
        esac ;;
      update-traffic) exit 0 ;;
    esac ;;
  "run deploy")
    # Snapshot the merged env file NOW. The script deletes it from a `trap ... EXIT`, so by the
    # time the test reads argv the path is dangling — and a test that silently could not read it
    # would assert nothing about what `apply` actually sends.
    prev=""
    for a in "$@"; do
      [ "$prev" = "--env-vars-file" ] && cp "$a" "$STUB_ENV_FILE_COPY"
      prev="$a"
    done
    exit "$STUB_DEPLOY_RC" ;;
  "run jobs")
    case "$3" in
      create)  exit "$STUB_JOB_CREATE_RC" ;;
      # Without --wait this returns 0 as soon as the execution is CREATED rather than when it
      # PASSES, so the exit code stops meaning "healthy" and the gate opens for every deploy.
      execute)
        case "$*" in *"--wait"*) ;; *) echo "stub: execute without --wait" >&2; exit 9 ;; esac
        exit "$STUB_JOB_EXECUTE_RC" ;;
      delete)  exit 0 ;;
    esac ;;
  "logging read")  printf '%s' "$STUB_LOG_OUTPUT"; exit 0 ;;
  "auth print-identity-token") echo stub-token; exit 0 ;;
esac
exit 0
"""


class Run:
    def __init__(
        self,
        proc: subprocess.CompletedProcess,
        calls: list[list[str]],
        env_vars_file: str | None = None,
    ):
        self.proc, self.calls = proc, calls
        # Contents of whatever was passed to --env-vars-file, captured before the script's
        # EXIT trap removed it. None when no such flag was passed.
        self.env_vars_file = env_vars_file

    @property
    def rc(self) -> int:
        return self.proc.returncode

    @property
    def err(self) -> str:
        return self.proc.stderr

    @property
    def out(self) -> str:
        return self.proc.stdout

    def _match(self, *head: str) -> list[list[str]]:
        return [c for c in self.calls if tuple(c[: len(head)]) == head]

    def deploy(self) -> list[str]:
        found = self._match("run", "deploy")
        assert len(found) == 1, f"expected exactly one `run deploy`, got {len(found)}"
        return found[0]

    def traffic_calls(self) -> list[list[str]]:
        return self._match("run", "services", "update-traffic")

    def flag(self, argv: list[str], name: str) -> str | None:
        """Value of `--name value` or `--name=value`, or None when absent."""
        for i, a in enumerate(argv):
            if a == name:
                return argv[i + 1] if i + 1 < len(argv) else ""
            if a.startswith(name + "="):
                return a.split("=", 1)[1]
        return None


def _run(
    tmp_path: Path,
    env_arg: str = "prod",
    tag: str = SHA,
    *,
    config: str | None = None,
    service_exists: bool = True,
    job_execute_rc: int = 0,
    job_create_rc: int = 0,
    deploy_rc: int = 0,
    log_output: str = "",
    ported_files: "bool | str" = False,
    curl_out: str = "404",
    overrides: "dict[str, str] | None" = None,
) -> Run:
    """Run the REAL deploy_gateway.sh against stubs.

    The script is copied so `$HERE` — the only path it derives from its own location — points at a
    scratch directory. That is what lets the ported-file tests control whether those two files
    exist without writing into the repo's own infra/gcp.
    """
    here = tmp_path / "infra_gcp"
    here.mkdir()
    script = here / "deploy_gateway.sh"
    shutil.copy2(SCRIPT, script)
    # True writes both; "env" / "secrets" write just one, for the half-ported state a run
    # interrupted partway through port_railway_env.py leaves behind.
    if ported_files in (True, "env"):
        (here / f"env.{env_arg}.gateway.yaml").write_text('SOME_PORTED_KEY: "ported-value"\n')
    if ported_files in (True, "secrets"):
        (here / f"secrets.{env_arg}.gateway.list").write_text("SOME_SECRET=SOME_SECRET:latest\n")

    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    (bin_dir / "gcloud").write_text(GCLOUD_STUB)
    (bin_dir / "curl").write_text('#!/bin/sh\nprintf %s "$STUB_CURL_OUT"\nexit 0\n')
    (bin_dir / "sleep").write_text("#!/bin/sh\nexit 0\n")
    for f in bin_dir.iterdir():
        f.chmod(0o755)

    calls_file = tmp_path / "calls.log"
    calls_file.touch()

    env = {
        **os.environ,
        "PATH": f"{bin_dir}:{os.environ['PATH']}",
        "GCLOUD": str(bin_dir / "gcloud"),
        "STUB_CALLS": str(calls_file),
        "STUB_TRAFFIC_JSON": TRAFFIC_JSON,
        "STUB_CAND_URL": f"https://{CANDIDATE_TAG}---gateway-abc.a.run.app",
        "STUB_SERVICE_URL": "https://gateway-abc.a.run.app",
        "STUB_SERVICE_EXISTS_RC": "0" if service_exists else "1",
        "STUB_JOB_EXECUTE_RC": str(job_execute_rc),
        "STUB_JOB_CREATE_RC": str(job_create_rc),
        "STUB_DEPLOY_RC": str(deploy_rc),
        "STUB_LOG_OUTPUT": log_output,
        "STUB_CURL_OUT": curl_out,
        "STUB_ENV_FILE_COPY": str(tmp_path / "env-vars-file.snapshot"),
    }
    env.pop("CONFIG", None)
    # The shape overrides are read from the ENVIRONMENT, so an operator who exported the incident
    # runbook's own `CONCURRENCY=20` in this shell would otherwise inject it into every test here -
    # and the default tests would pass while asserting nothing about the default.
    for shape_var in ("CONCURRENCY", "CONCURRENCY_LIMIT", "MIN_INSTANCES", "MAX_INSTANCES"):
        env.pop(shape_var, None)
    if config is not None:
        env["CONFIG"] = config
    env.update(overrides or {})

    proc = subprocess.run(
        ["bash", str(script), env_arg, tag],
        capture_output=True, text=True, timeout=120, env=env, cwd=str(tmp_path),
    )
    calls = [line.split("\t") for line in calls_file.read_text().splitlines() if line]
    snapshot = tmp_path / "env-vars-file.snapshot"
    return Run(proc, calls, snapshot.read_text() if snapshot.exists() else None)


