# ------------------------------------------------- the stamp cannot diverge from the image

@pytest.mark.parametrize("config,ported", [("preserve", False), ("apply", True)])
def test_the_image_and_the_stamp_name_the_same_commit(tmp_path, config, ported):
    """Both are `$TAG`. Pinned in BOTH modes, because a divergence in either is the same lie.

    Under `apply` the stamp travels in the merged env file rather than on the command line, so the
    file is read back and the two values compared.
    """
    r = _run(tmp_path, "prod", config=config, ported_files=ported)
    assert r.rc == 0, r.err
    argv = r.deploy()
    image = r.flag(argv, "--image")
    assert image is not None and image.endswith(f":{SHA}"), image

    if config == "preserve":
        stamped = r.flag(argv, "--update-env-vars").split("=", 1)[1]
    else:
        merged = r.env_vars_file
        assert merged is not None, "apply mode sent no --env-vars-file"
        stamped = [
            line.split(":", 1)[1].strip().strip('"')
            for line in merged.splitlines()
            if line.startswith("PIVOTA_COMMIT_SHA:")
        ][-1]
    assert stamped == image.rsplit(":", 1)[1]


def test_the_stamp_is_written_on_every_deploy_so_it_can_never_be_inherited(tmp_path):
    """The actual mechanism of the observed 7-commit under-report.

    Nobody set the image and the stamp to different values. A hand `gcloud run deploy --image X`
    passed no env flag at all, so Cloud Run carried the PREVIOUS revision's PIVOTA_COMMIT_SHA onto
    the new image. An absent flag is the failure, so absence is what this asserts against.
    """
    r = _run(tmp_path, "prod", tag=OTHER_SHA)
    argv = r.deploy()
    assert r.flag(argv, "--update-env-vars") == f"PIVOTA_COMMIT_SHA={OTHER_SHA}"


