def test_traffic_never_shifts_when_the_in_vpc_probe_fails(tmp_path):
    """Prod ingress is internal-and-cloud-load-balancing, so the direct curl always 404s and the
    in-VPC job is the probe that actually decides. Its exit code is the verdict."""
    # The log line says 200 and the job says otherwise. The verdict is the EXIT CODE: a scrape of
    # Cloud Logging must never be able to talk the gate INTO a promotion the probe refused.
    r = _run(tmp_path, "prod", job_execute_rc=1, log_output="PROBE_STATUS=200\n")
    assert r.rc == 1
    assert r.traffic_calls() == [], "promoted a candidate that failed its health check"


def test_traffic_never_shifts_when_the_probe_job_could_not_even_be_created(tmp_path):
    """`set -e` does not fire inside probe_health, so an unchecked create was entirely silent and
    "the job exited 0" rested on a job that never existed. A stale 200 in the logs must not rescue
    it either."""
    r = _run(tmp_path, "prod", job_create_rc=1, log_output="PROBE_STATUS=200\n")
    assert r.rc == 1
    assert r.traffic_calls() == []


def test_a_healthy_candidate_is_promoted_even_when_cloud_logging_has_not_caught_up(tmp_path):
    """The 2026-08-25 shape, ported here from deploy_backend.sh: the probe exits 0 but its log line
    is not queryable yet. Reading the verdict back out of Cloud Logging stranded a healthy backend
    revision at 0%; the gateway's copy of the gate had the same unbounded-ingestion-lag guess."""
    r = _run(tmp_path, "prod", job_execute_rc=0, log_output="")
    assert r.rc == 0, r.err
    assert any("--to-latest" in c for c in r.traffic_calls())


def test_stale_candidate_tags_are_swept_after_promotion(tmp_path):
    """The gate hand deploys skipped. A tagged revision is never garbage-collected and min-instances
    is 2, so each old candidate keeps instances running forever against the secret VERSIONS that
    were latest when they booted."""
    r = _run(tmp_path, "prod")
    removals = [c for c in r.traffic_calls() if any(a.startswith("--remove-tags") for a in c)]
    assert len(removals) == 1, f"expected one sweep, got {removals}"
    argv = removals[0]
    assert r.flag(argv, "--remove-tags") == "c-oldoldoldold"
    # The LIVE revision's tag serves 100% and must survive.
    assert CANDIDATE_TAG not in r.flag(argv, "--remove-tags")


def test_the_sweep_runs_on_a_preserve_deploy_too(tmp_path):
    """The whole point: the flow that was being bypassed must be reachable by the DEFAULT path."""
    r = _run(tmp_path, "prod", config=None)
    assert r.rc == 0, r.err
    assert any(any(a.startswith("--remove-tags") for a in c) for c in r.traffic_calls())


