def test_apply_rewrites_env_and_secrets_when_the_files_are_there(tmp_path):
    """`apply` must keep working — it is the only path that can configure a service from scratch."""
    r = _run(tmp_path, "prod", config="apply", ported_files=True)
    assert r.rc == 0, r.err
    argv = r.deploy()
    assert "--env-vars-file" in argv and "--set-secrets" in argv
    assert "--update-env-vars" not in argv
    secrets = r.flag(argv, "--set-secrets")
    # The DSNs port_railway_env.py's DROP_EXACT strips must still be re-mounted here.
    for name in ("DATABASE_URL=", "PCI_KB_DATABASE_URL=", "INGREDIENT_REFERENCE_DATABASE_URL="):
        assert name in secrets, f"{name} not re-mounted under CONFIG=apply"
    assert "SOME_SECRET=SOME_SECRET:latest" in secrets


