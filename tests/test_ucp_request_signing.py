"""RFC 9421 signing of the backend's outbound UCP calls -- the Python twin of the gateway signer.

THE VECTORS. tests/fixtures/ucp_request_signature_vectors.json is generated by the gateway's signer
(PIVOTA-Agent src/services/ucpBuyerAgentClient.js) and copied here verbatim. A merchant sees ONE
platform identity, so this signer must reproduce the gateway's Signature-Input, signature base and
Content-Digest byte for byte; the gateway pins the same file on its side
(tests/ucp_request_signature_vectors.test.js). ECDSA is randomised, so signatures are checked by
verifying them, never by comparing.

The key is TEST-ONLY -- the one already committed in the gateway's ucp_buyer_agent_client.test.js.
Hosts are placeholders.
"""

