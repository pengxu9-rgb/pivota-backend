@pytest.mark.parametrize("case", VECTORS["cases"], ids=[c["name"] for c in VECTORS["cases"]])
def test_python_signer_reproduces_the_gateway_vector(case):
    built = sig.build_signature_base(
        method=case["method"],
        url=case["url"],
        body=case["body"].encode("utf-8") if case["body"] is not None else None,
        ucp_agent=case["ucp_agent"],
        idempotency_key=case["idempotency_key"],
        keyid=VECTORS["public_jwk"]["kid"],
        created=VECTORS["created"],
        expires=VECTORS["expires"],
    )
    exp = case["expected"]
    assert built["covered"] == exp["covered"]
    assert built["base"] == exp["signature_base"]
    assert "sig1=" + built["params"] == exp["signature_input"]
    assert built["content_digest"] == exp["content_digest"]


@pytest.mark.parametrize("case", VECTORS["cases"], ids=[c["name"] for c in VECTORS["cases"]])
def test_the_gateway_signature_verifies_here(case):
    exp = case["expected"]
    assert _verify_raw(exp["signature_base"], _sig_bytes(exp["gateway_signature"]))


@pytest.mark.parametrize("case", VECTORS["cases"], ids=[c["name"] for c in VECTORS["cases"]])
def test_a_python_signature_over_the_vector_base_verifies(case):
    key, _ = sig.load_signing_key(TEST_PRIVATE_PEM, VECTORS["public_jwk"]["kid"])
    raw = sig.sign(case["expected"]["signature_base"], key)
    assert _verify_raw(case["expected"]["signature_base"], raw)
    assert not _verify_raw(case["expected"]["signature_base"] + "x", raw)


