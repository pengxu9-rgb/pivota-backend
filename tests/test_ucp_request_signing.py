_VECTORS_PATH = os.path.join(os.path.dirname(__file__), "fixtures", "ucp_request_signature_vectors.json")
with open(_VECTORS_PATH, encoding="utf-8") as fh:
    VECTORS = json.load(fh)

# The SAME sha256 is pinned in PIVOTA-Agent tests/ucp_request_signature_vectors.test.js. A regenerated or
# edited vector file fails here AND there until both pins move together, so the two copies cannot drift.
VECTORS_SHA256 = "c263a74407f74187f1d7ae3f2a7f6664a54186c5794caafe50c50138f4786b50"


def test_the_vector_file_is_byte_for_byte_the_gateway_copy():
    with open(_VECTORS_PATH, "rb") as fh:
        assert hashlib.sha256(fh.read()).hexdigest() == VECTORS_SHA256

TEST_PRIVATE_PEM = "\n".join(
    [
        "-----BEGIN PRIVATE KEY-----",
        "MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQg2fN8OxOlC9VwiMwu",
        "Q0tpTsXRIH3nnlwnWwQwLnsAQoKhRANCAASp8aRruLtbq+P9X5jOjbpOOrgSX+Mf",
        "rx2Rl5cYEhcK8JJbntMGQeGDoTXqmaJskgNtd81kC+TOUjRLfzvvVRU4",
        "-----END PRIVATE KEY-----",
        "",
    ]
)
PROFILE = "https://ucp.pivota.cc/.well-known/ucp-agent"


def _b64url_int(v: str) -> int:
    return int.from_bytes(base64.urlsafe_b64decode(v + "=" * (-len(v) % 4)), "big")


def _public_key():
    jwk = VECTORS["public_jwk"]
    return ec.EllipticCurvePublicNumbers(_b64url_int(jwk["x"]), _b64url_int(jwk["y"]), ec.SECP256R1()).public_key()


def _verify_raw(base: str, raw: bytes) -> bool:
    assert len(raw) == 64, "ECDSA P-256 must be raw r||s, 64 bytes, never DER"
    der = utils.encode_dss_signature(int.from_bytes(raw[:32], "big"), int.from_bytes(raw[32:], "big"))
    try:
        _public_key().verify(der, base.encode("utf-8"), ec.ECDSA(hashes.SHA256()))
        return True
    except InvalidSignature:
        return False


def _sig_bytes(header: str) -> bytes:
    return base64.b64decode(re.fullmatch(r"sig1=:(.*):", header).group(1))


