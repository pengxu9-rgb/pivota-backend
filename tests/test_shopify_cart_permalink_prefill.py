def _buyer(**overrides):
    fields = dict(
        email="ucp-probe@pivota.cc", first_name="Pivota", last_name="Probe",
        address1="1209 Orange Street", city="Wilmington", province="DE", zip="19801",
        country="US", phone="+12025550142",
    )
    fields.update(overrides)
    return CartPrefill(**fields)


def _pairs(url):
    """Split the query WITHOUT a parser that would normalise the literal brackets."""
    query = urlparse(url).query
    return [tuple(p.split("=", 1)) for p in query.split("&")]


