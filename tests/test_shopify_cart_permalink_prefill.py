def test_the_judydoll_values_produce_the_documented_shopify_keys_exactly():
    url = build_shopify_cart_permalink(
        shop_domain="judydoll.com", variant_id="50041364447509", click_id="clk_j", buyer=JUDYDOLL
    )
    assert url == JUDYDOLL_LINK
    assert cart_prefill_refusal(JUDYDOLL) is None


def test_a_non_ascii_city_round_trips_through_percent_encoding():
    city = "Chiyoda-ku 千代田区"
    url = build_shopify_cart_permalink(
        shop_domain="tieut.jp", variant_id="1", click_id="clk_t",
        buyer=_buyer(city=city, country="JP", province="JP-13", zip="100-0005"),
    )
    assert url is not None
    assert url.isascii()
    decoded = {k: unquote(v) for k, v in _pairs(url)}
    assert decoded["checkout[shipping_address][city]"] == city
    assert decoded["checkout[shipping_address][country]"] == "JP"


def test_empty_optional_fields_are_omitted_entirely_never_sent_empty():
    url = build_shopify_cart_permalink(
        shop_domain="s.com", variant_id="1", click_id="clk",
        buyer=_buyer(address2="", province=None, zip="   ", phone=None),
    )
    keys = [k for k, _ in _pairs(url)]
    for absent in ("address2", "province", "zip", "phone"):
        assert f"checkout[shipping_address][{absent}]" not in keys
    assert all(v for _, v in _pairs(url)), "no key may be emitted with an empty value"
    assert "=&" not in url and not url.endswith("=")


def test_address2_is_emitted_when_given():
    url = build_shopify_cart_permalink(
        shop_domain="s.com", variant_id="1", click_id="clk", buyer=_buyer(address2="Suite 5"),
    )
    assert "checkout[shipping_address][address2]=Suite%205" in url


def test_a_value_cannot_smuggle_extra_parameters():
    url = build_shopify_cart_permalink(
        shop_domain="s.com", variant_id="1", click_id="clk",
        buyer=_buyer(address1="1 Main&checkout[email]=evil@x.com#frag"),
    )
    keys = [k for k, _ in _pairs(url)]
    assert keys.count("checkout[email]") == 1
    assert "#" not in url
    assert dict(_pairs(url))["checkout[email]"] == "ucp-probe%40pivota.cc"


def test_a_lowercase_country_is_emitted_uppercase():
    url = build_shopify_cart_permalink(
        shop_domain="s.com", variant_id="1", click_id="clk", buyer=_buyer(country="us"))
    assert "checkout[shipping_address][country]=US" in url


