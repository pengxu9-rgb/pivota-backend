# --- redaction -----------------------------------------------------------------------------


def _pii_forms(value):
    return {value, quote(value, safe=""), quote_plus(value)}


def test_redaction_removes_every_buyer_value_and_keeps_host_path_and_click_id():
    red = redact_cart_permalink(JUDYDOLL_LINK)
    assert red.startswith("https://judydoll.com/cart/50041364447509:1?")
    assert "attributes[pivota_click_id]=clk_j" in red
    for value in ("ucp-probe@pivota.cc", "1209 Orange Street", "Wilmington", "19801", "+12025550142",
                  "Pivota", "Probe"):
        for form in _pii_forms(value):
            assert form not in red, form
    # keys survive, values become REDACTED
    assert "checkout[email]=REDACTED" in red
    assert red.count(REDACTED) == 9


def test_redaction_handles_the_percent_encoded_keys_shopify_re_emits_on_the_next_hop():
    hop = (
        "https://luafeejp.com/cart/52912527868213:1?attributes%5Bpivota_click_id%5D=clk_l"
        "&checkout%5Bemail%5D=ucp-probe%40pivota.cc"
        "&checkout%5Bshipping_address%5D%5Baddress1%5D=1-1+Marunouchi&cart_link_id=hNKeFU9Z"
    )
    red = redact_cart_permalink(hop)
    assert "ucp-probe" not in red and "Marunouchi" not in red
    assert "attributes%5Bpivota_click_id%5D=clk_l" in red
    assert urlparse(red).hostname == "luafeejp.com"
    assert urlparse(red).path == "/cart/52912527868213:1"


def test_redaction_also_covers_the_shop_pay_token_that_embeds_the_landing_url():
    hop = ("https://shop.app/checkout/10201629/cn/TOKEN/en-us/shoppay?shop_pay_token=eyJhbGci.PAYLOAD.sig"
           "&attributes%5Bpivota_click_id%5D=clk_p#section")
    red = redact_cart_permalink(hop)
    assert "PAYLOAD" not in red
    assert "#section" not in red
    assert "attributes%5Bpivota_click_id%5D=clk_p" in red


def test_redaction_drops_userinfo_and_redacts_a_bare_key():
    red = redact_cart_permalink("https://user:pw@s.com/cart/1:1?someone@example.com")
    assert "pw" not in red and "someone" not in red
    assert red == "https://s.com/cart/1:1?REDACTED"


def test_redaction_of_non_urls():
    assert redact_cart_permalink("") == ""
    assert redact_cart_permalink(None) == ""
    assert redact_cart_permalink("ucp-probe@pivota.cc") == REDACTED



