"""The prod alert for an A2A checkout held for a human (infra/gcp/setup_monitoring.sh, "prod: A2A checkout held for a
human"): its log filter matches the REAL line the worker writes when it holds a checkout, once per hold, and nothing
else; the policy is generated by the script's own `policy` generator and its text is the operator's runbook (list-held,
close-declined, the evidence rules, the one-business-day target, never re-run an apply), with no id or secret in it.

No cloud writes: the filters are parsed out of the shell source and evaluated locally (tests/test_reap_rail_alerts).
"""

from __future__ import annotations

import re
import types

import pytest

from test_reap_rail_alerts import (  # noqa: F401
    _entry, _filter, _threshold, matches, reap_policies, source, worker_log,
)

import services.payment_orchestration.a2a_rail_worker as worker

POLICY = "prod: A2A checkout held for a human"
METRIC = "a2a_rail_checkout_held"


async def _held_lines(monkeypatch, hold):
    """The lines the worker writes when it holds a checkout, through its real hold function and logger (the ledger
    write is stubbed: only the log line is under test)."""
    async def release_claim(*args, **kwargs):
        return None

    async def transition_as_holder(*args, **kwargs):
        return None

    async def settled(*args, **kwargs):
        return None

    monkeypatch.setattr(worker.ledger, "release_claim", release_claim)
    monkeypatch.setattr(worker.ledger, "transition_as_holder", transition_as_holder)
    monkeypatch.setattr(worker, "_settled", settled)
    step = types.SimpleNamespace(id="ap_" + "0" * 24, worker="alert-test")
    with worker_log() as lines:
        if hold == "checkout_hold":
            await worker._checkout_hold(step, worker.CHECKOUT_CONFIRM_UNRESOLVED)
        else:
            await worker._hold_before_paying(step, None, worker.CHECKOUT_SETUP_UNRESOLVED)
    return lines


@pytest.mark.parametrize("hold", ["checkout_hold", "hold_before_paying"])
async def test_the_real_hold_line_matches_once(source, monkeypatch, hold):
    log_filter = _filter(source, "A2A_CHECKOUT_HELD_FILTER")
    lines = await _held_lines(monkeypatch, hold)
    assert sum(matches(log_filter, _entry(line)) for line in lines) == 1, lines


def test_the_filter_matches_only_the_hold_line_on_the_worker(source):
    log_filter = _filter(source, "A2A_CHECKOUT_HELD_FILTER")
    line = "a2a_rail_worker: checkout held for a human purchase=ap_x code=checkout_payment_reached_declined"
    assert matches(log_filter, _entry(line))
    assert not matches(log_filter, _entry(line, service="web"))
    assert not matches(log_filter, _entry(line, resource_type="cloud_run_job"))
    # The poll job's per-tick summary counts held rows on EVERY tick (a re-tick is not a new hold).
    assert not matches(log_filter, _entry("a2a_rail_purchase_poll: {'checkout_held': 1}"))
    # The VIC path's own hold is a different line (its own close path).
    assert not matches(log_filter, _entry("a2a_rail_worker: VIC order held for a human purchase=ap_x code=y"))


def test_the_metric_is_created_by_the_script_and_the_policy_reads_it(source):
    assert f"upsert_log_metric {METRIC} " in source
    policy = reap_policies()[POLICY]
    t = _threshold(policy)
    assert t["filter"] == f'metric.type="logging.googleapis.com/user/{METRIC}" AND resource.type="cloud_run_revision"'
    assert t["duration"] == "0s" and t["thresholdValue"] == 0 and t["comparison"] == "COMPARISON_GT"
    assert t["aggregations"][0]["alignmentPeriod"] == "900s"
    assert policy["notificationChannels"] == ["projects/p/notificationChannels/1"]
    # Through upsert_on_new_metric (its log metric is this script's own), like the Reap human queue.
    assert re.search(rf'^upsert_on_new_metric "{re.escape(POLICY)}" "\$\(policy ', source, re.M)


def test_the_policy_text_is_the_runbook_and_carries_no_id_or_secret():
    doc = reap_policies()[POLICY]["documentation"]["content"]
    for must in ("python -m jobs.a2a_rail_operator list-held", "close-declined", "checkout_payment_reached_declined",
                 "within one business day", "never more than 7 days", "at least 1 hour after the hold",
                 "no authorization was approved or captured", "no order exists at the merchant",
                 "Never re-run an apply", "A2A_RAIL_OPERATOR_CLOSE_DECLINED_ENABLED is set only in that one-off",
                 "resolve-held refuses every payment-reached hold", "docs/agent_purchases_routes.md"):
        assert must in doc, must
    assert not re.search(r"\b(ap|pp|rp)_[0-9a-f]{8,}", doc), "no purchase id"
    for secret in ("API_KEY", "CONTEXT_SECRET", "DATABASE_URL", "agent-dev", "http"):
        assert secret not in doc, secret
